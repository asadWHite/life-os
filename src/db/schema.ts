import {
  pgTable,
  uuid,
  text,
  integer,
  boolean,
  timestamp,
  date,
  jsonb,
  primaryKey,
  index,
  uniqueIndex,
} from "drizzle-orm/pg-core";

/* ------------------------------------------------------------------ */
/* Auth / users                                                        */
/* ------------------------------------------------------------------ */

export const users = pgTable(
  "users",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    email: text("email").notNull().unique(),
    passwordHash: text("password_hash").notNull().default(""),
    googleId: text("google_id").unique(),
    firstName: text("first_name").notNull().default(""),
    lastName: text("last_name").notNull().default(""),
    avatarUrl: text("avatar_url"),
    dateOfBirth: date("date_of_birth"),
    lifeStage: text("life_stage"), // school | university | working | other
    language: text("language").notNull().default("uz"), // uz | en | ru
    timezone: text("timezone").notNull().default("Asia/Tashkent"),
    appearance: text("appearance").notNull().default("system"), // light | dark | system
    onboardingStep: integer("onboarding_step").notNull().default(0),
    onboardingCompleted: boolean("onboarding_completed").notNull().default(false),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("users_email_idx").on(t.email)],
);

export const authSessions = pgTable(
  "auth_sessions",
  {
    tokenHash: text("token_hash").primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    expiresAt: timestamp("expires_at", { withTimezone: true }).notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("auth_sessions_user_idx").on(t.userId)],
);

/* ------------------------------------------------------------------ */
/* Preferences (1:1 with user)                                         */
/* ------------------------------------------------------------------ */

export const preferences = pgTable("preferences", {
  userId: uuid("user_id")
    .primaryKey()
    .references(() => users.id, { onDelete: "cascade" }),
  interests: text("interests").array().notNull().default([]),
  challenges: text("challenges").array().notNull().default([]),
  wakeTime: text("wake_time"), // "06:30"
  bedTime: text("bed_time"), // "22:30"
  workHours: text("work_hours"), // free-form slot label, e.g. "morning"
  planningStyle: text("planning_style"), // light | structured | flexible
  freeTime: text("free_time"), // "<1h" | "1-2h" | "2-4h" | "4h+"
  phoneHabits: jsonb("phone_habits").notNull().default({}), // { morning, beforeBed, reduceLate }
  notifications: jsonb("notifications").notNull().default({}), // { bedtime, task, focus, wake }
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

export const sleepSchedules = pgTable("sleep_schedules", {
  userId: uuid("user_id")
    .primaryKey()
    .references(() => users.id, { onDelete: "cascade" }),
  targetBedtime: text("target_bedtime").notNull().default("22:30"),
  targetWake: text("target_wake").notNull().default("06:30"),
  targetMinutes: integer("target_minutes").notNull().default(480),
  weekdays: integer("weekdays").array().notNull().default([1, 2, 3, 4, 5, 6, 0]),
  remindBedtime: boolean("remind_bedtime").notNull().default(false),
  updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
});

/* ------------------------------------------------------------------ */
/* Tasks                                                               */
/* ------------------------------------------------------------------ */

export const tasks = pgTable(
  "tasks",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    goalId: uuid("goal_id").references(() => goals.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    description: text("description").notNull().default(""),
    status: text("status").notNull().default("pending"), // pending | completed
    priority: text("priority").notNull().default("normal"), // low | normal | high
    dueDate: date("due_date").notNull(),
    startTime: text("start_time"), // optional "18:00"
    reminderMinutes: integer("reminder_minutes"), // optional minutes before start
    suggested: boolean("suggested").notNull().default(false), // generated by initial plan
    completedAt: timestamp("completed_at", { withTimezone: true }),
    deletedAt: timestamp("deleted_at", { withTimezone: true }), // soft delete preserves history
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    index("tasks_user_due_idx").on(t.userId, t.dueDate),
    index("tasks_user_status_idx").on(t.userId, t.status),
  ],
);

/* ------------------------------------------------------------------ */
/* Habits                                                              */
/* ------------------------------------------------------------------ */

export const habits = pgTable(
  "habits",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    frequency: text("frequency").notNull().default("daily"), // daily | weekly
    targetPerWeek: integer("target_per_week").notNull().default(7),
    active: boolean("active").notNull().default(true),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("habits_user_idx").on(t.userId)],
);

export const habitCompletions = pgTable(
  "habit_completions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    habitId: uuid("habit_id")
      .notNull()
      .references(() => habits.id, { onDelete: "cascade" }),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    date: date("date").notNull(),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [
    uniqueIndex("habit_completions_unique").on(t.habitId, t.date),
    index("habit_completions_user_date_idx").on(t.userId, t.date),
  ],
);

/* ------------------------------------------------------------------ */
/* Goals                                                               */
/* ------------------------------------------------------------------ */

export const goals = pgTable(
  "goals",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    name: text("name").notNull(),
    description: text("description").notNull().default(""),
    status: text("status").notNull().default("active"), // active | completed | archived
    targetDate: date("target_date"),
    completedAt: timestamp("completed_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("goals_user_idx").on(t.userId)],
);

/* ------------------------------------------------------------------ */
/* Sleep sessions                                                      */
/* ------------------------------------------------------------------ */

export const sleepSessions = pgTable(
  "sleep_sessions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    startedAt: timestamp("started_at", { withTimezone: true }).notNull(),
    endedAt: timestamp("ended_at", { withTimezone: true }),
    durationMinutes: integer("duration_minutes"),
    state: text("state").notNull().default("active"), // active | completed | discarded
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
    updatedAt: timestamp("updated_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("sleep_user_started_idx").on(t.userId, t.startedAt)],
);

/* ------------------------------------------------------------------ */
/* Focus sessions (lamp)                                               */
/* ------------------------------------------------------------------ */

export const focusSessions = pgTable(
  "focus_sessions",
  {
    id: uuid("id").defaultRandom().primaryKey(),
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    taskId: uuid("task_id").references(() => tasks.id, { onDelete: "set null" }),
    title: text("title").notNull(),
    plannedStart: timestamp("planned_start", { withTimezone: true }).notNull(),
    plannedEnd: timestamp("planned_end", { withTimezone: true }).notNull(),
    completedAt: timestamp("completed_at", { withTimezone: true }), // user ended after >=15 min
    cancelledAt: timestamp("cancelled_at", { withTimezone: true }),
    createdAt: timestamp("created_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [index("focus_user_idx").on(t.userId, t.plannedStart)],
);

/* ------------------------------------------------------------------ */
/* Achievements (definitions live in code; unlocks persisted here)     */
/* ------------------------------------------------------------------ */

export const userAchievements = pgTable(
  "user_achievements",
  {
    userId: uuid("user_id")
      .notNull()
      .references(() => users.id, { onDelete: "cascade" }),
    code: text("code").notNull(),
    unlockedAt: timestamp("unlocked_at", { withTimezone: true }).notNull().defaultNow(),
  },
  (t) => [primaryKey({ columns: [t.userId, t.code] })],
);

export type User = typeof users.$inferSelect;
export type Task = typeof tasks.$inferSelect;
export type Habit = typeof habits.$inferSelect;
export type Goal = typeof goals.$inferSelect;
export type SleepSession = typeof sleepSessions.$inferSelect;
export type FocusSession = typeof focusSessions.$inferSelect;
export type SleepSchedule = typeof sleepSchedules.$inferSelect;
export type Preferences = typeof preferences.$inferSelect;
